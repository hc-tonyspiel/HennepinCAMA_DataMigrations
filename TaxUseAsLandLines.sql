INSERT INTO @TAX_USE_LAND_LINES_TABLE
SELECT  --TUS_ID,
        TUS_PID AS VISION_ID,
        --TUS_BID AS BUILDING_ID,
        REM_ACCT_NUM AS PID,
        BLD_BLDG_NUM,
        TUS_LINE_NUM AS LAND_LINE_NUM,
        TUS_TAXPROPERTYTYPE_LTP_CODE AS TAX_PROPERTY_TYPE_CODE,
        TUS_TAXPROPERTYTYPE_DESC AS TAX_PROPERTY_TYPE_DESC,
        TUS_DESCRIPTION AS USE_DESCRIPTION,
        TUS_TAX_USE_CODE,
        CAST(CASE ACRES
            WHEN 0 THEN SQ_FT_FROM_LEGAL_AREA / @SQ_FT_IN_ACRE
            ELSE ACRES
        END AS NUMERIC(19,2)) AS ACRES,
        CAST(CASE SQ_FT_FROM_ACRES
            WHEN 0 THEN SQ_FT_FROM_LEGAL_AREA
            ELSE SQ_FT_FROM_ACRES
        END AS NUMERIC(19,2)) AS SQ_FT,
        SQ_FT_FROM_LEGAL_AREA AS LEGAL_PARCEL_LOT_SIZE_SQ_FT
FROM (
    SELECT  t.TUS_ID,
            t.TUS_PID,
            t.TUS_BID,
            t.TUS_LINE_NUM,
            t.TUS_COMPONENT_TYPE,
            t.TUS_LINE_CODE,
            t.TUS_DESCRIPTION, 
            t.TUS_TAX_USE_CODE,
            CASE t.TUS_ACRES
            WHEN 0 THEN 
                CASE l.LND_UNIT_TYPE
                    WHEN 'AC' THEN L.LND_UNITS --ACREAGE
                    ELSE 0
                END
            ELSE
                t.TUS_ACRES
            END + ISNULL(REMAINING_HGA_SITE.TUS_ACRES, 0) - ISNULL(EXTRA_HGA_SITE.TUS_ACRES, 0) AS ACRES,
            @SQ_FT_IN_ACRE * CASE t.TUS_ACRES
                                WHEN 0 THEN 
                                    CASE l.LND_UNIT_TYPE
                                        WHEN 'AC' THEN L.LND_UNITS --ACREAGE
                                        ELSE 0
                                    END
                                ELSE
                                    t.TUS_ACRES + ISNULL(REMAINING_HGA_SITE.TUS_ACRES, 0) - ISNULL(EXTRA_HGA_SITE.TUS_ACRES, 0)
                                END AS SQ_FT_FROM_ACRES,
            r.REM_LEGAL_AREA AS SQ_FT_FROM_LEGAL_AREA,
            t.TUS_TAXPROPERTYTYPE_LTP_CODE,
            t.TUS_TAXPROPERTYTYPE_DESC,
            t.TUS_PARENT_ID,
            r.REM_ACCT_NUM,
            b.BLD_BLDG_NUM
    FROM (
        SELECT *
        FROM (
	        SELECT *
	        FROM [CAMA_PROD].REAL_PROP.TAX_USE
	        WHERE TUS_PARENT_ID IS NULL
        ) AS p

        UNION 

        SELECT c.*
        FROM [CAMA_PROD].REAL_PROP.TAX_USE p
        INNER JOIN [CAMA_PROD].REAL_PROP.TAX_USE c ON c.TUS_PARENT_ID = p.TUS_ID
        WHERE p.TUS_LINE_CODE != 'OB'
    ) t
    INNER JOIN REAL_PROP.REALMAST r WITH(NOLOCK) ON r.REM_PID = t.TUS_PID AND r.REM_PARCEL_STATUS = 'A'
    INNER JOIN REAL_PROP.BLDG b WITH(NOLOCK) ON b.BLD_PID = r.REM_PID AND t.TUS_BID = b.BLD_BID
    INNER JOIN REAL_PROP.LAND l ON r.REM_PID = l.LND_PID AND t.TUS_LINE_NUM = l.LND_LINE_NUM
    LEFT JOIN (
        SELECT TUS_ID,
            TUS_PID,
            TUS_BID,
            TUS_LINE_NUM,
            TUS_COMPONENT_TYPE,
            TUS_LINE_CODE,
            TUS_DESCRIPTION,
            TUS_TAX_USE_CODE,
            TUS_ACRES, 
            TUS_ACRES * 43560.0000 AS TUS_SQFT,
            TUS_TAXPROPERTYTYPE_LTP_CODE,
            TUS_TAXPROPERTYTYPE_DESC,
            TUS_PARENT_ID 
        FROM REAL_PROP.TAX_USE 
        WHERE   TUS_COMPONENT_TYPE = 'LAND'
            AND TUS_LINE_CODE = 'M' 
            AND TUS_TAX_USE_CODE = '1400' 
            AND TUS_PARENT_ID IS NOT NULL 
            AND TUS_TAXPROPERTYTYPE_LTP_CODE = 'F' 
            AND TUS_LINE_NUM > 1
    ) REMAINING_HGA_SITE ON REMAINING_HGA_SITE.TUS_PID = t.TUS_PID AND t.TUS_LINE_NUM = 1 
    LEFT JOIN (
        SELECT TUS_ID,
            TUS_PID,
            TUS_BID,
            TUS_LINE_NUM,
            TUS_COMPONENT_TYPE,
            TUS_LINE_CODE,
            TUS_DESCRIPTION,
            TUS_TAX_USE_CODE,
            TUS_ACRES, 
            TUS_ACRES * 43560.0000 AS TUS_SQFT,
            TUS_TAXPROPERTYTYPE_LTP_CODE,
            TUS_TAXPROPERTYTYPE_DESC,
            TUS_PARENT_ID 
        FROM REAL_PROP.TAX_USE 
        WHERE   TUS_COMPONENT_TYPE = 'LAND'
            AND TUS_LINE_CODE = 'M' 
            AND TUS_TAX_USE_CODE = '1400' 
            AND TUS_PARENT_ID IS NOT NULL 
            AND TUS_TAXPROPERTYTYPE_LTP_CODE = 'F' 
            AND TUS_LINE_NUM > 1
    ) EXTRA_HGA_SITE ON EXTRA_HGA_SITE.TUS_PID = t.TUS_PID AND t.TUS_LINE_NUM = 2 
    WHERE t.TUS_LINE_CODE = 'L'
        --AND  t.TUS_TAXPROPERTYTYPE_LTP_CODE NOT IN (--361,042/ 417,331 WITH THIS UNCOMMENTED / COMMENTED
        --    'X', 
        --    'Y',
        --    'LR',
        --    'LA',
        --    'LL'
        --) 
        AND t.TUS_ACRES + 
            CASE t.TUS_ACRES
                WHEN 0 THEN 
                    CASE l.LND_UNITS
                        WHEN 0 THEN r.REM_LEGAL_AREA
                        ELSE l.LND_UNITS
                    END
                ELSE (t.TUS_ACRES * 43560.0000) 
            END > 0
) l
ORDER BY PID, TUS_BID, TUS_LINE_NUM

--SELECT COUNT(1) FROM @TAX_USE_LAND_LINES_TABLE

SELECT  t.VID,
        t.PID,
        BUILDING_NUM,
        LINE_NUM,
        PROPERTY_TYPE_DESC + ' (' + PROPERTY_TYPE_CODE + ')' AS PROPERTY_TYPE,
        USE_DESCRIPTION,
        VALUATION_USE_CODE,
        ACRES,
        SQ_FT,
        LEGAL_PARCEL_LOT_SIZE_SQ_FT,
        CAST(CASE LEGAL_PARCEL_LOT_SIZE_SQ_FT
            WHEN 0 THEN 100.00
            ELSE 
                CASE
                    WHEN SQ_FT - LEGAL_PARCEL_LOT_SIZE_SQ_FT > 0 THEN (SQ_FT - LEGAL_PARCEL_LOT_SIZE_SQ_FT) / LEGAL_PARCEL_LOT_SIZE_SQ_FT * 100.00
                    WHEN LEGAL_PARCEL_LOT_SIZE_SQ_FT - SQ_FT > 0 THEN (SQ_FT - LEGAL_PARCEL_LOT_SIZE_SQ_FT) / LEGAL_PARCEL_LOT_SIZE_SQ_FT * 100.00
                    WHEN LEGAL_PARCEL_LOT_SIZE_SQ_FT - SQ_FT = 0 THEN 0
                END
        END AS NUMERIC(19,2)) AS PERCENT_DIFFERENCE
FROM @TAX_USE_LAND_LINES_TABLE t
